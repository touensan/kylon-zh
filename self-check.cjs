for (const chinese of dictionary.values()) assert.equal(translate(chinese), chinese);
const manifest = JSON.parse(fs.readFileSync(path.join(__dirname, 'extension/manifest.json'), 'utf8'));
assert.equal(manifest.manifest_version, 3);
assert.deepEqual(manifest.permissions, ['storage']);
assert.deepEqual(manifest.content_scripts[0].matches, ['https://app.kylon.io/*']);
assert.equal(manifest.content_scripts[0].world || 'ISOLATED', 'ISOLATED');
assert.equal(Object.hasOwn(manifest, 'host_permissions'), false);
assert.equal(Object.hasOwn(manifest, 'background'), false);
assert.deepEqual(manifest.content_scripts[0].js, ['phrases.js', 'content.js']);
assert.deepEqual(manifest.content_scripts[1].matches, ['https://docs.kylon.io/*']);
assert.deepEqual(manifest.content_scripts[1].js, ['phrases.js', 'docs-phrases.js', 'content.js']);
assert.ok(dictionary.size > 5500);
const docsContext = {
  module: {exports:{}},
  require: filename => require(path.join(__dirname,'extension',filename)),
  location: {hostname:'docs.kylon.io'}
};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'extension/content.js'),'utf8'),docsContext);
const translateDocs = docsContext.module.exports.translate;
assert.equal(translateDocs('クイックスタート'),'快速开始');
assert.equal(translateDocs('データベース App とカスタム App'),'数据库应用与自定义应用');
assert.equal(translateDocs('Kylon を始める入口は、大きく 2 つあります。'),'Kylon 主要提供两种入门方式。');
