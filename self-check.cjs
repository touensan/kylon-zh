assert.equal(translateDocs('Kylon home page dark logo'),'Kylon 首页深色标志');
assert.equal(translateDocs('Navigate to header'),'跳转到标题');
assert.equal(translateDocs('Copy the contents from the code block'),'复制代码块内容');
assert.equal(translateDocs('kylon agent link --provider codex'),'kylon agent link --provider codex');
assert.equal(translateDocs('/api/v1/proxy/tools'),'\/api/v1/proxy/tools');
assert.equal(translateDocs('pak_example_key'),'pak_example_key');
for (const chinese of docsContext.module.exports.dictionary.values()) assert.equal(translateDocs(chinese),chinese);
